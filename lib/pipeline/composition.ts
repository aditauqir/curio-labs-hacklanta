// Stage E: selected concept + asset plan -> a structured design document.
//
// Layout is produced deterministically from the concept's composition
// strategy. A language model is not asked to emit coordinates: it is bad at
// arithmetic, and a layout that fails its own overflow check is worse than a
// plain one that does not. The model's creative decisions (which strategy,
// which treatment, which colour story) are what drive the template choice.
import type { Concept, CompositionStrategy, VisualLanguage } from "./concepts.ts";
import type { PlannedAsset } from "./assets.ts";
import type { StructuredBrief } from "./brief.ts";
import {
  type DesignDocument,
  type DesignElement,
  type Provenance,
  type TextElement,
  defaultFrame,
} from "./document.ts";
import { glyphRatio, reflowText } from "./layout.ts";

type Palette = { background: string; foreground: string; accent: string; muted: string };
type Fonts = { heading: string; body: string; mono: string };

const MONO = "ui-monospace, Menlo, Consolas, monospace";

/** Font stacks are web-safe families: the server renderer has no font loader. */
const FONT_SETS: Record<string, Fonts> = {
  serif: { heading: "Georgia, Times New Roman, serif", body: "Helvetica Neue, Helvetica, Arial, sans-serif", mono: MONO },
  grotesk: { heading: "Helvetica Neue, Helvetica, Arial, sans-serif", body: "Helvetica Neue, Helvetica, Arial, sans-serif", mono: MONO },
  mixed: { heading: "Georgia, Times New Roman, serif", body: "Verdana, Geneva, sans-serif", mono: MONO },
};

const HUES: Array<[RegExp, number]> = [
  [/turquoise|teal|aqua/, 174],
  [/terracotta|rust|brick|coral/, 14],
  [/butter yellow|mustard|ochre|gold/, 45],
  [/cobalt|navy|royal blue|indigo/, 224],
  [/lavender|violet|plum|purple/, 278],
  [/pink|magenta|fuchsia/, 326],
  [/orange|tangerine|apricot/, 28],
  [/olive|moss|sage|forest|green/, 106],
  [/red|vermilion|scarlet/, 4],
  [/blue|sky|azure/, 202],
];

function hueFromConcept(concept: Concept) {
  const words = `${concept.colorStrategy} ${concept.materialStrategy} ${concept.title}`.toLocaleLowerCase();
  const matches = HUES.filter(([pattern]) => pattern.test(words)).map(([, hue]) => hue);
  if (matches.length > 0) return matches[0];

  // The fallback is still driven by Gemini's returned concept, so a new
  // title/material story does not collapse into one of four fixed presets.
  let hash = 2166136261;
  for (const character of words) {
    hash ^= character.charCodeAt(0);
    hash = Math.imul(hash, 16777619);
  }
  return Math.abs(hash) % 360;
}

function hsl(hue: number, saturation: number, lightness: number) {
  const s = saturation / 100;
  const l = lightness / 100;
  const chroma = (1 - Math.abs(2 * l - 1)) * s;
  const x = chroma * (1 - Math.abs(((hue / 60) % 2) - 1));
  const m = l - chroma / 2;
  const [r, g, b] = hue < 60 ? [chroma, x, 0]
    : hue < 120 ? [x, chroma, 0]
      : hue < 180 ? [0, chroma, x]
        : hue < 240 ? [0, x, chroma]
          : hue < 300 ? [x, 0, chroma]
            : [chroma, 0, x];
  return `#${[r, g, b].map((value) => Math.round((value + m) * 255).toString(16).padStart(2, "0")).join("").toUpperCase()}`;
}

function generatedPalette(concept: Concept): Palette {
  const words = `${concept.colorStrategy} ${concept.materialStrategy}`.toLocaleLowerCase();
  const dark = /dark|night|black|charcoal|noir/.test(words);
  const matchedHues = HUES.filter(([pattern]) => pattern.test(words)).map(([, matchedHue]) => matchedHue);
  const hue = matchedHues[0] ?? hueFromConcept(concept);
  const secondaryHue = matchedHues.find((matchedHue) => matchedHue !== hue) ?? (hue + 54) % 360;
  return dark
    ? {
        background: hsl(hue, 20, 10),
        foreground: hsl((hue + 36) % 360, 18, 94),
        accent: hsl(secondaryHue, 78, 62),
        muted: hsl(hue, 14, 54),
      }
    : {
        background: hsl(hue, 28, 94),
        foreground: hsl((hue + 190) % 360, 26, 18),
        accent: hsl(secondaryHue, 72, 46),
        muted: hsl(hue, 18, 56),
      };
}

/** Maps the concept's own words onto a concrete palette and type pairing. */
export function stylesFor(concept: Concept): { palette: Palette; fonts: Fonts } {
  const type = `${concept.typographyDirection}`.toLocaleLowerCase();

  const palette = concept.palette ?? generatedPalette(concept);

  const fonts =
    /serif|editorial|display serif|garamond/.test(type) ? FONT_SETS.serif
    : /mixed|contrast|pairing/.test(type) ? FONT_SETS.mixed
    : FONT_SETS.grotesk;

  return { palette, fonts };
}

const PROCEDURAL: Provenance = {
  source: "procedural",
  assetId: null,
  creator: null,
  sourceUrl: null,
  license: "Generated by Curio Labs renderer",
  cleared: true,
  generator: "composition-planner",
  note: null,
};

type TextSpec = {
  id: string;
  name: string;
  content: string;
  role: "heading" | "body";
  weight: number;
  color: string;
  align: "left" | "center" | "right";
  transform: "none" | "uppercase";
  required: boolean;
  /** Frame box as canvas fractions. Height is recomputed to fit the text. */
  x: number;
  y: number;
  width: number;
  anchor: TextElement["frame"]["anchor"];
  maxSize: number;
  minSize: number;
  lineHeight: number;
  letterSpacing: number;
  italic?: boolean;
};

/**
 * Chooses a type size that actually fits, then sizes the frame to the text.
 * Doing this here is what keeps the deterministic overflow check passing
 * instead of reporting a failure the planner could have avoided.
 */
function buildText(spec: TextSpec, canvas: { width: number; height: number }): TextElement {
  const element: TextElement = {
    id: spec.id,
    name: spec.name,
    type: "text",
    text: spec.content,
    role: spec.role,
    size: spec.maxSize,
    weight: spec.weight,
    letterSpacing: spec.letterSpacing,
    lineHeight: spec.lineHeight,
    align: spec.align,
    transform: spec.transform,
    color: spec.color,
    italic: spec.italic ?? false,
    required: spec.required,
    frame: defaultFrame({ anchor: spec.anchor, x: spec.x, y: spec.y, width: spec.width, height: 0.1 }),
    rotation: 0,
    opacity: 1,
    blendMode: "normal",
    locked: false,
    editable: true,
    provenance: PROCEDURAL,
  };

  const boxWidthPx = spec.width * canvas.width;
  const ratio = glyphRatio(element);
  const hardLines = spec.content.split("\n").map((line) => line.trim()).filter(Boolean);
  const longest = hardLines.reduce((max, line) => Math.max(max, line.length), 1);

  // Largest size at which the longest hard line still fits. The 0.97 is a
  // deliberate margin: fitting to exactly the box width lets a sub-pixel
  // rounding difference flip the renderer's wrap to an extra line, which then
  // overflows the frame this function just sized.
  const fitted = (boxWidthPx * 0.97) / (longest * (ratio + spec.letterSpacing));
  const sizePx = Math.max(
    spec.minSize * canvas.width,
    Math.min(spec.maxSize * canvas.width, fitted),
  );
  element.size = sizePx / canvas.width;

  // Size the frame with the shared reflow helper so the planner and the
  // overflow check are measuring the same thing.
  return reflowText(element, canvas);
}

function rule(id: string, y: number, color: string, opacity: number): DesignElement {
  return {
    id,
    name: "Rule",
    type: "shape",
    shape: "rect",
    fill: color,
    stroke: null,
    strokeWidth: 0,
    radius: 0,
    frame: defaultFrame({ anchor: "top-left", x: 0.09, y, width: 0.82, height: 0.0022 }),
    rotation: 0,
    opacity,
    blendMode: "normal",
    locked: false,
    editable: true,
    provenance: PROCEDURAL,
  };
}

function imagePlaceholder(asset: PlannedAsset, frame: Partial<TextElement["frame"]>): DesignElement {
  return {
    id: asset.id,
    name: asset.role,
    type: "image",
    assetId: null,
    fit: "cover",
    description: asset.description,
    frame: defaultFrame(frame),
    rotation: 0,
    opacity: 1,
    blendMode: "normal",
    locked: false,
    editable: true,
    provenance: {
      source: asset.source,
      assetId: null,
      creator: null,
      sourceUrl: null,
      license: asset.license,
      cleared: asset.cleared,
      generator: asset.generator,
      note: asset.note,
    },
  };
}

