export type CompositionInput = {
  brief: StructuredBrief;
  concept: Concept;
  assets: PlannedAsset[];
};

/** One template per composition strategy. Each returns ordered elements. */
function layoutFor(
  strategy: CompositionStrategy,
  input: CompositionInput,
  palette: Palette,
  canvas: { width: number; height: number },
): DesignElement[] {
  const { brief } = input;
  const headline = brief.requiredText.headline;
  const sub = brief.requiredText.subheadline;
  const cta = brief.requiredText.callToAction;
  const details = brief.requiredText.details.slice(0, 4).join("   ");
  const hero = input.assets.find((asset) => asset.type === "hero-image");

  const elements: DesignElement[] = [];
  const align = strategy === "centred-stack" ? "center" : strategy === "edge-anchored" ? "right" : "left";
  const anchorH = align === "center" ? "center" : align === "right" ? "right" : "left";

  const common = {
    align: align as "left" | "center" | "right",
    required: true,
    role: "heading" as const,
    transform: "uppercase" as const,
    lineHeight: 0.95,
    letterSpacing: -0.01,
  };

  switch (strategy) {
    case "full-bleed-image": {
      if (hero) elements.push(imagePlaceholder(hero, { anchor: "top-left", x: 0, y: 0, width: 1, height: 1 }));
      elements.push({
        id: "scrim",
        name: "Legibility scrim",
        type: "shape",
        shape: "rect",
        fill: palette.background,
        stroke: null,
        strokeWidth: 0,
        radius: 0,
        frame: defaultFrame({ anchor: "bottom-left", x: 0, y: 0, width: 1, height: 0.45 }),
        rotation: 0,
        opacity: 0.82,
        blendMode: "normal",
        locked: false,
        editable: true,
        provenance: PROCEDURAL,
      });
      elements.push(
        buildText(
          { ...common, id: "headline", name: "Headline", content: headline, weight: 700,
            color: palette.foreground, x: 0.08, y: 0.26, width: 0.84,
            anchor: `bottom-${anchorH}` as TextElement["frame"]["anchor"], maxSize: 0.11, minSize: 0.05 },
          canvas,
        ),
      );
      break;
    }

    case "centred-stack": {
      elements.push(
        buildText(
          { ...common, id: "headline", name: "Headline", content: headline, weight: 700,
            color: palette.foreground, x: 0, y: 0.22, width: 0.8,
            anchor: "top-center", maxSize: 0.14, minSize: 0.05 },
          canvas,
        ),
      );
      elements.push(rule("rule-top", 0.18, palette.muted, 0.6));
      break;
    }

    case "diagonal-break": {
      elements.push({
        id: "field",
        name: "Diagonal field",
        type: "shape",
        shape: "rect",
        fill: palette.accent,
        stroke: null,
        strokeWidth: 0,
        radius: 0,
        frame: defaultFrame({ anchor: "top-left", x: -0.15, y: 0.05, width: 1.3, height: 0.34 }),
        rotation: -8,
        opacity: 1,
        blendMode: "normal",
        locked: false,
        editable: true,
        provenance: PROCEDURAL,
      });
      elements.push(
        buildText(
          { ...common, id: "headline", name: "Headline", content: headline, weight: 700,
            color: palette.foreground, x: 0.08, y: 0.46, width: 0.84,
            anchor: "top-left", maxSize: 0.14, minSize: 0.05 },
          canvas,
        ),
      );
      break;
    }

    case "edge-anchored": {
      elements.push({
        id: "edge-bar",
        name: "Edge bar",
        type: "shape",
        shape: "rect",
        fill: palette.accent,
        stroke: null,
        strokeWidth: 0,
        radius: 0,
        frame: defaultFrame({ anchor: "top-left", x: 0, y: 0, width: 0.026, height: 1 }),
        rotation: 0,
        opacity: 1,
        blendMode: "normal",
        locked: false,
        editable: true,
        provenance: PROCEDURAL,
      });
      elements.push(
        buildText(
          { ...common, id: "headline", name: "Headline", content: headline, weight: 700,
            color: palette.foreground, x: 0.08, y: 0.24, width: 0.8,
            anchor: "top-right", maxSize: 0.13, minSize: 0.05 },
          canvas,
        ),
      );
      break;
    }

    case "modular-grid": {
      elements.push(rule("rule-top", 0.1, palette.muted, 0.5));
      elements.push(rule("rule-mid", 0.52, palette.muted, 0.5));
      elements.push(
        buildText(
          { ...common, id: "headline", name: "Headline", content: headline, weight: 700,
            color: palette.foreground, x: 0.09, y: 0.14, width: 0.82,
            anchor: "top-left", maxSize: 0.1, minSize: 0.04 },
          canvas,
        ),
      );
      break;
    }

    case "typographic-stack": {
      elements.push(
        buildText(
          { ...common, id: "headline", name: "Headline", content: headline, weight: 700,
            color: palette.foreground, x: 0.08, y: 0.16, width: 0.84,
            anchor: "top-left", maxSize: 0.17, minSize: 0.06, lineHeight: 0.86 },
          canvas,
        ),
      );
      break;
    }

    case "asymmetric-grid":
    default: {
      elements.push(
        buildText(
          { ...common, id: "headline", name: "Headline", content: headline, weight: 700,
            color: palette.foreground, x: 0.08, y: 0.2, width: 0.72,
            anchor: "top-left", maxSize: 0.13, minSize: 0.05 },
          canvas,
        ),
      );
      if (hero) {
        elements.unshift(
          imagePlaceholder(hero, { anchor: "bottom-right", x: 0.06, y: 0.08, width: 0.46, height: 0.3 }),
        );
      }
      break;
    }
  }

  // The model chooses a visual language separately from the structural
  // layout. This is what prevents every concept from becoming the same bar,
  // circle, and lime accent with a different headline.
  elements.push(...visualLanguageElements(input.concept.visualLanguage, palette));

  // A concept that asked for a hero image must get one in every strategy, not
  // only the two templates that place it explicitly. Dropping a planned asset
  // here would make the asset plan a promise the design quietly breaks.
  if (hero && !elements.some((element) => element.type === "image")) {
    elements.unshift(
      imagePlaceholder(hero, { anchor: "middle-center", x: 0, y: 0.04, width: 0.7, height: 0.26 }),
    );
  }

  // Shared supporting copy, placed relative to the bottom edge so it survives
  // any aspect ratio change.
  let cursor = 0.3;
  if (sub) {
    elements.push(
      buildText(
        { id: "subheadline", name: "Subheadline", content: sub, role: "body", weight: 400,
          color: palette.foreground, align: align as "left" | "center" | "right", transform: "none",
          required: true, x: align === "center" ? 0 : 0.08, y: cursor, width: 0.7,
          anchor: `bottom-${anchorH}` as TextElement["frame"]["anchor"],
          maxSize: 0.032, minSize: 0.018, lineHeight: 1.3, letterSpacing: 0 },
        canvas,
      ),
    );
    cursor -= 0.08;
  }
  if (details) {
    elements.push(
      buildText(
        { id: "details", name: "Details", content: details, role: "body", weight: 600,
          color: palette.foreground, align: align as "left" | "center" | "right", transform: "uppercase",
          required: true, x: align === "center" ? 0 : 0.08, y: 0.14, width: 0.84,
          anchor: `bottom-${anchorH}` as TextElement["frame"]["anchor"],
          maxSize: 0.024, minSize: 0.014, lineHeight: 1.2, letterSpacing: 0.06 },
        canvas,
      ),
    );
  }
  if (cta) {
    elements.push(
      buildText(
        { id: "cta", name: "Call to action", content: cta, role: "body", weight: 700,
          color: palette.accent, align: align as "left" | "center" | "right", transform: "uppercase",
          required: true, x: align === "center" ? 0 : 0.08, y: 0.07, width: 0.84,
          anchor: `bottom-${anchorH}` as TextElement["frame"]["anchor"],
          maxSize: 0.022, minSize: 0.013, lineHeight: 1.2, letterSpacing: 0.08 },
        canvas,
      ),
    );
  }

  // Material strategy becomes a real layer rather than a note on a slide.
  if (/grain|riso|newsprint|texture|halftone/.test(input.concept.materialStrategy.toLocaleLowerCase())) {
    elements.unshift({
      id: "texture-ground",
      name: "Print grain",
      type: "texture",
      pattern: /halftone/.test(input.concept.materialStrategy.toLocaleLowerCase()) ? "halftone" : "grain",
      color: palette.muted,
      scale: 0.004,
      frame: defaultFrame({ anchor: "top-left", x: 0, y: 0, width: 1, height: 1 }),
      rotation: 0,
      opacity: 0.18,
      blendMode: "multiply",
      locked: false,
      editable: true,
      provenance: PROCEDURAL,
    });
  }

  return elements;
}

export function composeDesign(input: CompositionInput): DesignDocument {
  const { palette, fonts } = stylesFor(input.concept);
  const canvas = { width: input.brief.dimensions.width, height: input.brief.dimensions.height };

  return {
    schemaVersion: 1,
    canvas: { ...canvas, background: palette.background, safeMargin: 0.06 },
    typography: fonts,
    palette,
    elements: layoutFor(input.concept.compositionStrategy, input, palette, canvas),
    meta: {
      conceptId: input.concept.id,
      format: input.brief.outputFormat,
      notes: [
        `Composition strategy: ${input.concept.compositionStrategy}`,
        `Concept: ${input.concept.title}`,
        ...input.concept.avoid.slice(0, 3).map((entry) => `Avoid: ${entry}`),
      ],
    },
  };
}
