"""
Curio Labs: procedural texture / halftone asset generator.

Everything here is deterministic (seeded) and original: no third-party imagery,
no generative model. Parameters come from the style recipes in analysis/recipes
(pitch_px, angle_deg, std_dev, roughness, blur_sigma, ...).

Usage:  python make_assets.py --out ../        (run from anywhere)

Conventions (also written into assets_manifest.json):
  * halftone threshold maps (kind=halftone_threshold), 8-bit grayscale, tileable:
        out_light = (luminance > map)      # map is HIGH at dot centres -> dark ink dots
    angle_deg is the lattice-row direction in IMAGE coordinates (x right, y down,
    i.e. clockwise on screen), modulo 90 for dots.
  * grain / paper / overlays are centred or biased for the blend mode in blend_hint.
"""
