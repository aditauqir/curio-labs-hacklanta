# ----------------------------------------------------------------------------- utils
def u8(a):
    return np.clip(np.rint(a), 0, 255).astype(np.uint8)


def save(rel, arr):
    p = OUT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    if arr.dtype != np.uint8:
        arr = u8(arr)
    Image.fromarray(arr).save(p, optimize=True)
    return p


def reg(id, rel, kind, size, blend, tileable, params, achieved=None, notes="", seed=None,
        opacity_hint=None, extra=None):
    d = {
        "id": id,
        "file": rel,
        "kind": kind,
        "size": list(size),
        "blend_hint": blend,
        "tileable": tileable,
        "params": params,
        "achieved": achieved or {},
        "opacity_hint": opacity_hint,
        "seed": seed,
        "notes": notes,
        "license": "CC0-1.0",
        "provenance": "Procedurally generated by tools/make_assets.py v%s; original work, no third-party content." % VERSION,
    }
    if extra:
        d.update(extra)
    ASSETS.append(d)


def nf(shape, sigma, rng, wrap=True):
    """Unit-variance gaussian noise, optionally blurred (wrap => tileable)."""
    n = rng.standard_normal(shape)
    if np.any(np.asarray(sigma) > 0):
        n = ndi.gaussian_filter(n, sigma, mode="wrap" if wrap else "reflect")
    return (n - n.mean()) / n.std()


def smoothstep(a, b, x):
    t = np.clip((x - a) / (b - a), 0, 1)
    return t * t * (3 - 2 * t)


def equalize(d, q=1e-4):
    """Rank-transform d to (0,1) with tie handling (equal-ish values share a rank)."""
    di = np.round(np.asarray(d) / q).astype(np.int64)
    vals, inv, counts = np.unique(di.ravel(), return_inverse=True, return_counts=True)
    cum = np.cumsum(counts) - counts / 2.0
    return (cum[inv] / di.size).reshape(di.shape)


# ----------------------------------------------------------------------------- halftone
def find_lattice(angle_deg, pitch, N, pmax=32):
    """
    Rational-angle square lattice that tiles an NxN image exactly.
    Row vector ~ (p, q)/L at angle atan2(q, p); pitch P = N / (m * L) for integer m.
    Returns (p, q, m, P, theta_deg).
    """
    target = angle_deg % 90.0
    best = None
    for p in range(0, pmax + 1):
        for q in range(0, pmax + 1):
            if (p, q) == (0, 0) or math.gcd(p, q) != 1:
                continue
            L = math.hypot(p, q)
            th = math.degrees(math.atan2(q, p))
            m0 = round(N / (pitch * L))
            for m in (m0 - 1, m0, m0 + 1):
                if m < 1:
                    continue
                P = N / (m * L)
                if P < 2.5:
                    continue
                a_err = abs(((th - target + 45.0) % 90.0) - 45.0)       # degrees
                p_err = abs(P - pitch) / pitch * 100.0                  # percent
                score = a_err / 1.0 + p_err / 1.5
                if best is None or score < best[0]:
                    best = (score, p, q, m, P, th)
    _, p, q, m, P, th = best
    return p, q, m, P, th


def lattice_uv(N, p, q, P):
    L = math.hypot(p, q)
    y, x = np.mgrid[0:N, 0:N]
    x = x + 0.5
    y = y + 0.5
    a = (x * p + y * q) / (L * P)
    b = (-x * q + y * p) / (L * P)
    return a - np.floor(a), b - np.floor(b)


def dot_distance(u, v, shape):
    cx, cy = u - 0.5, v - 0.5
    if shape == "round":
        return np.hypot(cx, cy)
    if shape == "square":
        return np.maximum(np.abs(cx), np.abs(cy))
    if shape == "ellipse":
        return np.hypot(cx, cy * 1.35)
    if shape == "diamond":
        return np.abs(cx) + np.abs(cy)
    raise ValueError(shape)


def ht_dot(id, shape, pitch, angle, seed, jitter=0.0, srcnote="", notes="", N=N_HT, group="halftone"):
    p, q, m, P, th = find_lattice(angle, pitch, N)
    u, v = lattice_uv(N, p, q, P)
    d = dot_distance(u, v, shape)
    if jitter:
        d = d + np.random.default_rng(seed).normal(0, jitter, d.shape)
    M = 255.0 * (1.0 - equalize(d))
    rel = "%s/%s.png" % (group, id)
    save(rel, M)
    reg(id, rel, "halftone_threshold", (N, N), "threshold", True,
        {"shape": shape, "pitch_px": pitch, "angle_deg": angle, "jitter": jitter},
        {"pitch_px": round(P, 3), "angle_deg": round(th % 90.0, 2), "lattice_pq": [p, q], "lattice_repeats": m},
        notes=notes, seed=seed if jitter else None)
    print("  %-34s target %.2f px @ %.1f  ->  %.3f px @ %.2f" % (id, pitch, angle, P, th % 90.0))


def ht_line(id, pitch, seed=None, N=N_HT, notes="", group="halftone"):
    k = max(1, round(N / pitch))
    P = N / k
    y = (np.arange(N) + 0.5) / P
    d = np.abs((y - np.floor(y)) - 0.5)
    r = equalize(d)
    M = np.tile((255.0 * (1.0 - r))[:, None], (1, N))
    rel = "%s/%s.png" % (group, id)
    save(rel, M)
    reg(id, rel, "halftone_threshold", (N, N), "threshold", True,
        {"shape": "line_horizontal", "pitch_px": pitch, "angle_deg": 90.0},
        {"pitch_px": round(P, 3), "angle_deg": 90.0, "line_orientation": "horizontal"},
        notes=notes)
    print("  %-34s target %.2f px  ->  %.3f px (horizontal lines)" % (id, pitch, P))


def bayer(n):
    if n == 1:
        return np.array([[0]])
    b = bayer(n // 2)
    return np.block([[4 * b + 0, 4 * b + 2], [4 * b + 3, 4 * b + 1]])


def ht_bayer(n, N=N_HT):
    B = bayer(n)
    M = (B + 0.5) / (n * n) * 255.0
    M = np.tile(M, (N // n, N // n))
    id = "ht_bayer%d" % n
    rel = "halftone/%s.png" % id
    save(rel, M)
    reg(id, rel, "halftone_threshold", (N, N), "threshold", True,
        {"shape": "ordered_dither", "matrix": n}, {"matrix": n},
        notes="Ordered (Bayer) dither; use for 1-bit / retro / thermal-print looks.")


def ht_blue(seed=11, N=N_HT):
    rng = np.random.default_rng(seed)
    n = rng.standard_normal((N, N))
    hp = n - ndi.gaussian_filter(n, 1.6, mode="wrap")     # high-pass => blue-ish spectrum
    M = 255.0 * equalize(hp, q=1e-3)
    id = "ht_stochastic_blue"
    rel = "halftone/%s.png" % id
    save(rel, M)
    reg(id, rel, "halftone_threshold", (N, N), "threshold", True,
        {"shape": "stochastic_blue_noise"}, {}, seed=seed,
        notes="FM / stochastic screen (approximate blue noise). No visible dot lattice.")


# ----------------------------------------------------------------------------- patterns
def sqwave(x, cell):
    return np.clip(0.5 + np.sin(np.pi * x / cell) * cell / np.pi, 0, 1)


def pattern_checker(pitch, N=N_HT):
    k = max(1, round(N / (2 * pitch)))
    cell = N / (2 * k)
    x = (np.arange(N) + 0.5)
    a = sqwave(x, cell)[None, :]
    b = sqwave(x, cell)[:, None]
    c = a * b + (1 - a) * (1 - b)
    id = "pattern_checker_p15"
    rel = "patterns/%s.png" % id
    save(rel, 255.0 * c)
    reg(id, rel, "pattern", (N, N), "multiply", True,
        {"cell_px": pitch}, {"cell_px": round(cell, 3)},
        notes="Anti-aliased black/white checkerboard raster (underground flyer divider / barcode feel). "
              "Use as mask for gradient/colour swaps or multiply/overlay.")
    print("  %-34s target %.2f px -> %.3f px" % (id, pitch, cell))


def pattern_scanlines(pitch=4, N=N_HT, depth=0.55):
    y = (np.arange(N) + 0.5)
    prof = 1.0 - depth * (0.5 + 0.5 * np.cos(2 * np.pi * y / pitch))
    M = np.tile((255.0 * prof)[:, None], (1, N))
    id = "pattern_scanlines_crt_p4"
    rel = "patterns/%s.png" % id
    save(rel, M)
    reg(id, rel, "pattern", (N, N), "multiply", True,
        {"pitch_px": pitch, "depth": depth, "orientation": "horizontal"},
        {"pitch_px": pitch, "rows_dark": 2, "rows_light": 2},
        notes="CRT-style horizontal raster lines, 255 = no effect. Multiply over duotone/tritone art "
              "(cyberpunk HUD / hazard-amber look).")


def pattern_rings(W=W_POSTER, H=H_POSTER, pitch=5.01, seed=5):
    y, x = np.mgrid[0:H, 0:W]
    c1 = (W * 0.38, H * 0.42)
    c2 = (W * 0.38 + 90, H * 0.42 + 40)
    r1 = np.hypot(x - c1[0], y - c1[1])
    r2 = np.hypot(x - c2[0], y - c2[1])
    pat = 0.5 * np.sin(2 * np.pi * r1 / pitch) + 0.5 * np.sin(2 * np.pi * r2 / (pitch * 1.06))
    id = "pattern_interference_rings_p5"
    rel = "patterns/%s.png" % id
    save(rel, 128.0 + 100.0 * pat)
    reg(id, rel, "pattern", (W, H), "overlay", False,
        {"pitch_px": pitch, "type": "sinusoidal_interference_rings"},
        {"pitch_px": pitch, "moire_ratio": 1.06},
        notes="Two offset concentric sinusoids => moire interference rings (thermal / psychedelic techno). "
              "Overlay or soft-light at 0.2-0.5 opacity; can also drive displacement.")


