def grain_mono(id, std, sigma, seed, group="grain", notes="", N=N_GRAIN, family="mono"):
    rng = np.random.default_rng(seed)
    g = nf((N, N), sigma, rng)
    arr = 128.0 + std * g
    rel = "%s/%s.png" % (group, id)
    save(rel, arr)
    reg(id, rel, "grain", (N, N), "overlay", True,
        {"std_dev": std, "family": family}, {"grain_sigma_px": sigma, "mean": 128},
        notes=notes or "Mid-grey centred (128) monochrome grain for overlay/soft-light.", seed=seed)


def grain_silver(id, std, seed, N=N_GRAIN):
    rng = np.random.default_rng(seed)
    g = 0.75 * nf((N, N), 1.0, rng) + 0.45 * nf((N, N), 2.4, rng)
    g = g * (1.0 + 0.30 * nf((N, N), 8.0, rng))
    g = (g - g.mean()) / g.std()
    rel = "grain/%s.png" % id
    save(rel, 128.0 + std * g)
    reg(id, rel, "grain", (N, N), "overlay", True,
        {"std_dev": std, "family": "silver_gelatin"}, {"mean": 128, "clumping": 0.3},
        notes="Coarser, clumpy silver-gelatin grain (documentary / newsprint photo look).", seed=seed)


def grain_toner(id, std, seed, N=N_GRAIN):
    rng = np.random.default_rng(seed)
    g = rng.laplace(size=(N, N))
    g = ndi.gaussian_filter(g, 0.55, mode="wrap")
    g = (g - g.mean()) / g.std()
    rel = "grain/%s.png" % id
    save(rel, 128.0 + std * g)
    reg(id, rel, "grain", (N, N), "overlay", True,
        {"std_dev": std, "family": "toner_grit"}, {"mean": 128, "distribution": "laplace"},
        notes="Heavy-tailed grit (more outliers than gaussian) for photocopier / toner texture.", seed=seed)


def grain_chroma(id, std, seed, N=N_GRAIN):
    rng = np.random.default_rng(seed)
    luma = nf((N, N), 0.7, rng)
    chans = []
    for _ in range(3):
        c = 0.6 * luma + 0.8 * nf((N, N), 0.7, rng)
        c = (c - c.mean()) / c.std()
        chans.append(128.0 + std * c)
    rel = "grain/%s.png" % id
    save(rel, np.stack(chans, axis=-1))
    reg(id, rel, "grain", (N, N), "overlay", True,
        {"std_dev": std, "family": "chromatic"}, {"mean": 128, "channels": 3, "luma_correlation": 0.6},
        notes="RGB colour noise (digital / thermal-camera feel). Overlay at 0.2-0.4.", seed=seed)


# ----------------------------------------------------------------------------- paper
def paper(id, roughness, seed, mean=236.0, fiber=1.0, mottle=1.0, specks=700, stain=0.0, notes="", N=N_PAPER):
    rng = np.random.default_rng(seed)
    mott = 0.55 * nf((N, N), 48, rng) + 0.35 * nf((N, N), 18, rng) + 0.25 * nf((N, N), 6, rng)
    mott /= mott.std()
    fib = nf((N, N), (0.6, 9.0), rng) + nf((N, N), (9.0, 0.6), rng) + 0.6 * nf((N, N), (0.5, 4.0), rng)
    fib /= fib.std()
    fine = nf((N, N), 0.7, rng)
    arr = mean + roughness * 1.1 * mottle * mott + fiber * 2.2 * fib + 1.6 * fine
    layer = np.zeros((N, N))
    ys = rng.integers(0, N, specks)
    xs = rng.integers(0, N, specks)
    layer[ys, xs] = -rng.uniform(15, 55, specks)
    arr = arr + ndi.gaussian_filter(layer, 0.8, mode="wrap") * 3.0
    if stain:
        s = nf((N, N), 140, rng)
        arr = arr - stain * 14.0 * smoothstep(0.2, 1.6, s)
    arr = arr + (mean - arr.mean())
    rel = "paper/%s.png" % id
    save(rel, arr)
    reg(id, rel, "paper", (N, N), "multiply", True,
        {"roughness": roughness}, {"mean": round(float(np.clip(arr, 0, 255).mean()), 1), "fiber": fiber, "specks": specks, "stain": stain},
        notes=notes or "Neutral grey paper: multiply at 0.12-0.2 opacity, then tint with the recipe paper colour.", seed=seed)


