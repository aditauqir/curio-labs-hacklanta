def speckle(id, seed, density=0.0012, N=N_PAPER):
    rng = np.random.default_rng(seed)
    n = int(N * N * density)
    sp = np.zeros((N, N))
    sp[rng.integers(0, N, n), rng.integers(0, N, n)] = rng.uniform(0.3, 1.0, n)
    sp = ndi.gaussian_filter(sp, 0.8, mode="wrap") * 6.0
    rel = "overlays/%s.png" % id
    save(rel, 255.0 * (1.0 - np.clip(sp, 0, 0.85)))
    reg(id, rel, "overlay", (N, N), "multiply", True,
        {"density": density}, {"specks": n},
        notes="Dark toner/dust specks on white (255 = no effect). Multiply.", seed=seed)


def creases(id, count, seed, W=W_POSTER, H=H_POSTER):
    rng = np.random.default_rng(seed)
    S = 2
    im = Image.new("L", (W * S, H * S), 0)
    dr = ImageDraw.Draw(im)
    for _ in range(count):
        horiz = rng.random() < 0.5
        npts = 70
        t = np.linspace(0, 1, npts)
        walk = np.cumsum(rng.normal(0, 0.9, npts))
        if horiz:
            y0 = rng.uniform(0.15, 0.85) * H
            slope = rng.uniform(-0.04, 0.04)
            xs = t * W
            ys = y0 + slope * (xs - W / 2) + walk
        else:
            x0 = rng.uniform(0.15, 0.85) * W
            slope = rng.uniform(-0.04, 0.04)
            ys = t * H
            xs = x0 + slope * (ys - H / 2) + walk
        for i in range(npts - 1):
            if rng.random() < 0.08:
                continue
            dr.line([(xs[i] * S, ys[i] * S), (xs[i + 1] * S, ys[i + 1] * S)],
                    fill=int(rng.uniform(110, 255)), width=int(rng.integers(2, 5)))
    a = np.asarray(im.resize((W, H), Image.LANCZOS), dtype=np.float64)
    out = 0.85 * a + 0.55 * ndi.gaussian_filter(a, 4.0) + 0.45 * ndi.gaussian_filter(a, 18.0)
    out = out + np.abs(rng.normal(0, 2.0, out.shape))
    rel = "overlays/%s.png" % id
    save(rel, out)
    reg(id, rel, "overlay", (W, H), "screen", False,
        {"crease_count": count}, {"creases": count},
        notes="Black ground with light fold/crease lines and soft glow. Screen at 0.25-0.4 (photocopier fold marks).",
        seed=seed)


def edge_blotch(id, seed, W=W_POSTER, H=H_POSTER):
    rng = np.random.default_rng(seed)
    y, x = np.mgrid[0:H, 0:W]
    dist = np.minimum.reduce([x, W - 1 - x, y, H - 1 - y]).astype(np.float64)
    edgew = np.clip(1 - dist / 260.0, 0, 1) ** 1.6
    f = (nf((H, W), 60, rng, False) + 0.8 * nf((H, W), 22, rng, False)
         + 0.6 * nf((H, W), 7, rng, False) + 0.5 * nf((H, W), 2, rng, False))
    f /= f.std()
    t = f * 0.5 + edgew * 1.6 - 0.9
    ink = smoothstep(0.0, 0.5, t)
    rel = "overlays/%s.png" % id
    save(rel, 255.0 * (1.0 - 0.92 * ink))
    reg(id, rel, "overlay", (W, H), "multiply", False, {}, {},
        notes="Ragged dark toner blotches concentrated at the canvas edge (photocopy distress). Multiply.",
        seed=seed)


def cloud(id, sigma, seed, warp=False, N=N_PAPER):
    rng = np.random.default_rng(seed)
    f = 0.9 * nf((N, N), sigma * 2, rng) + 1.0 * nf((N, N), sigma, rng) + 0.55 * nf((N, N), sigma / 2, rng) \
        + 0.30 * nf((N, N), sigma / 4, rng) + 0.15 * nf((N, N), sigma / 8, rng)
    f = (f - f.mean()) / f.std()
    if warp:
        # gentle, smooth displacement (no fold-over => no hard crease edges under soft-light)
        dx = 34.0 * nf((N, N), sigma * 2.0, rng)
        dy = 34.0 * nf((N, N), sigma * 2.0, rng)
        Y, X = np.mgrid[0:N, 0:N].astype(np.float64)
        f = ndi.map_coordinates(f, [Y + dy, X + dx], order=1, mode="grid-wrap")
        f = (f - f.mean()) / f.std()
    rel = "overlays/%s.png" % id
    save(rel, 128.0 + 42.0 * f)
    reg(id, rel, "overlay", (N, N), "soft_light", True,
        {"blur_sigma": sigma, "warped": warp}, {"mean": 128, "std": 42},
        notes="Fractal atmospheric smoke / cloud field, tileable. Soft-light at 0.3-0.5 for airbrushed haze.", seed=seed)


# ----------------------------------------------------------------------------- vector-ish
def render_mask(prims, W, H, S=2):
    im = Image.new("L", (W * S, H * S), 0)
    dr = ImageDraw.Draw(im)
    for pr in prims:
        kind, geom, val, w = pr
        if kind == "line":
            x1, y1, x2, y2 = geom
            dr.line([(x1 * S, y1 * S), (x2 * S, y2 * S)], fill=val, width=max(1, int(round(w * S))))
        elif kind == "circle":
            cx, cy, r = geom
            dr.ellipse([(cx - r) * S, (cy - r) * S, (cx + r) * S, (cy + r) * S], outline=val, width=max(1, int(round(w * S))))
    return np.asarray(im.resize((W, H), Image.LANCZOS), dtype=np.float64)


def svg_from_prims(prims, W, H, bg=None, stroke="#ffffff"):
    out = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">' % (W, H, W, H)]
    if bg:
        out.append('<rect width="100%%" height="100%%" fill="%s"/>' % bg)
    out.append('<g fill="none" stroke="%s" stroke-linecap="round">' % stroke)
    for kind, geom, val, w in prims:
        op = round(val / 255.0, 3)
        if kind == "line":
            out.append('<line x1="%.2f" y1="%.2f" x2="%.2f" y2="%.2f" stroke-width="%s" stroke-opacity="%s"/>' % (*geom, w, op))
        else:
            out.append('<circle cx="%.2f" cy="%.2f" r="%.2f" stroke-width="%s" stroke-opacity="%s"/>' % (*geom, w, op))
    out.append("</g></svg>")
    return "\n".join(out)


def vec_grid(W=W_POSTER, H=H_POSTER):
    P = []
    for x in range(0, W + 1, 128):
        major = x % 512 == 0
        P.append(("line", (x, 0, x, H), 170 if major else 85, 1))
    for y in range(0, H + 1, 128):
        major = y % 512 == 0
        P.append(("line", (0, y, W, y), 170 if major else 85, 1))
    for x in range(0, W + 1, 32):
        P.append(("line", (x, 0, x, 10 if x % 128 else 22), 200, 1))
        P.append(("line", (x, H, x, H - (10 if x % 128 else 22)), 200, 1))
    for y in range(0, H + 1, 32):
        P.append(("line", (0, y, 10 if y % 128 else 22, y), 200, 1))
        P.append(("line", (W, y, W - (10 if y % 128 else 22), y), 200, 1))
    for x in range(0, W + 1, 512):
        for y in range(0, H + 1, 512):
            P.append(("line", (x - 14, y, x + 14, y), 255, 1))
            P.append(("line", (x, y - 14, x, y + 14), 255, 1))
    cx, cy = W / 2, H / 2
    for r in (256, 512, 768):
        P.append(("circle", (cx, cy, r), 200, 1))
    P.append(("line", (0, 0, W, H), 110, 1))
    P.append(("line", (W, 0, 0, H), 110, 1))
    id = "vec_wireframe_coordinate_grid"
    save("vector/%s.png" % id, render_mask(P, W, H))
    (OUT / "vector" / (id + ".svg")).write_text(svg_from_prims(P, W, H, bg="#000000"))
    reg(id, "vector/%s.png" % id, "vector", (W, H), "screen", False, {"stroke_px": 1},
        {"stroke_px": 1, "svg": "vector/%s.svg" % id},
        notes="1px technical coordinate grid, ticks, registration crosses and target circles on black. "
              "Screen at 0.3-0.5 (HUD / wireframe layer).")


def vec_flower(W=W_POSTER, H=H_POSTER, R=170):
    cx, cy = W / 2, H / 2
    P = []
    pts = []
    for i in range(-3, 4):
        for j in range(-3, 4):
            x = i * R + j * R / 2
            y = j * R * math.sqrt(3) / 2
            if math.hypot(x, y) <= 2 * R + 1e-6:
                pts.append((x, y))
    for x, y in pts:
        P.append(("circle", (cx + x, cy + y, R), 255, 1))
    P.append(("circle", (cx, cy, 3 * R), 255, 1))
    P.append(("circle", (cx, cy, 3 * R + 12), 160, 1))
    for k in range(6):
        a1 = math.radians(60 * k)
        a2 = math.radians(60 * (k + 2))
        P.append(("line", (cx + 3 * R * math.cos(a1), cy + 3 * R * math.sin(a1),
                           cx + 3 * R * math.cos(a2), cy + 3 * R * math.sin(a2)), 120, 1))
    id = "vec_sacred_flower_of_life"
    save("vector/%s.png" % id, render_mask(P, W, H))
    (OUT / "vector" / (id + ".svg")).write_text(svg_from_prims(P, W, H, bg="#000000"))
    reg(id, "vector/%s.png" % id, "vector", (W, H), "screen", False, {"stroke_px": 1, "radius": R},
        {"circles": len(pts) + 2, "svg": "vector/%s.svg" % id},
        notes="Flower-of-life sacred geometry wireframe, 1px lines on black. Screen/add over thermal or iridescent art.")


def vec_target(S=2048, bands=14, ink="#0f121b"):
    R = S / 2 - 40
    rgb = tuple(int(ink[i:i + 2], 16) for i in (1, 3, 5))
    im = Image.new("L", (S * 2, S * 2), 0)
    dr = ImageDraw.Draw(im)
    for i in range(bands):
        r = R * (1 - i / bands)
        # canvas is supersampled 2x (size 2S, centre S), so radius is 2r in canvas pixels
        dr.ellipse([S - 2 * r, S - 2 * r, S + 2 * r, S + 2 * r], fill=255 if i % 2 == 0 else 0)
    a = np.asarray(im.resize((S, S), Image.LANCZOS))
    rgba = np.zeros((S, S, 4), dtype=np.uint8)
    rgba[..., 0], rgba[..., 1], rgba[..., 2] = rgb
    rgba[..., 3] = a
    id = "vec_concentric_target"
    save("vector/%s.png" % id, rgba)
    svg = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">' % (S, S, S, S)]
    bw = R / bands
    for i in range(0, bands, 2):
        r_out = R * (1 - i / bands)
        r_mid = r_out - bw / 2
        svg.append('<circle cx="%d" cy="%d" r="%.2f" fill="none" stroke="%s" stroke-width="%.2f"/>' % (S / 2, S / 2, r_mid, ink, bw))
    svg.append("</svg>")
    (OUT / "vector" / (id + ".svg")).write_text("\n".join(svg))
    reg(id, "vector/%s.png" % id, "vector", (S, S), "normal", False, {"bands": bands, "ink": ink},
        {"svg": "vector/%s.svg" % id, "alpha": True},
        notes="Concentric target / bullseye motif (Swiss-techno), transparent RGBA in recipe ink colour #0f121b. "
              "Recolour by replacing RGB; scale freely via the SVG.")


